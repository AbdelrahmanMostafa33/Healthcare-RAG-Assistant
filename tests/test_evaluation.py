    assert table.loc["Behaviour pass: answer"].tolist() == ["1/2", "1/2"]
    assert table.loc["Behaviour pass: refuse"].tolist() == ["-", "-"]
    assert table.loc["Abstention recall", "RAG"] == "0.90" and table.loc["Abstention precision", "RAG"] == "-"


